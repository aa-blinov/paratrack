package web

import "net/http"

func (s *Server) registerProtectedAPIRoutes(mux *http.ServeMux, apiAuth func(http.Handler) http.Handler) {
	// JSON API routes are registered directly on the top-level mux. The
	// apiAuth middleware makes authentication failures return JSON 401.
	// Form and HTMX submissions under /api paths remain on the pages mux
	// above, where unauthenticated requests redirect to the login page.
	api := func(method, path string, h http.HandlerFunc) {
		mux.Handle(method+" "+path, apiAuth(h))
	}

	api("GET", "/api/active", s.mine(s.handleAPIActive))
	api("GET", "/api/dashboard", s.mine(s.handleAPIDashboard))
	api("GET", "/api/reports.csv", s.handleCSV)
	api("POST", "/api/start", s.mine(s.handleStart))
	api("POST", "/api/sessions/{id}/stop", s.mine(s.handleStop))
	api("POST", "/api/sessions/{id}/reopen", s.mine(s.handleReopen))
	api("POST", "/api/sessions/{id}/pause", s.mine(s.handlePause))
	api("POST", "/api/sessions/{id}/resume", s.mine(s.handleResume))
	api("POST", "/api/focus/{name}", s.mine(s.handleFocus))
	api("POST", "/api/active/pause-all", s.mine(s.handlePauseAll))
	api("POST", "/api/active/stop-all", s.mine(s.handleStopAll))
	api("POST", "/api/sessions/backfill", s.handleBackfill)
	api("PATCH", "/api/sessions/{id}", s.handleUpdateSession)
	api("DELETE", "/api/sessions/{id}", s.handleDeleteSession)
	api("GET", "/api/tasks", s.module("tasks", s.handleTasksAPIList))
	api("POST", "/api/tasks", s.module("tasks", s.handleTaskCreate))
	api("POST", "/api/tasks/{id}", s.module("tasks", s.handleTaskUpdate))
	api("POST", "/api/tasks/{id}/status", s.module("tasks", s.handleTaskStatus))
	api("POST", "/api/tasks/{id}/comments", s.module("tasks", s.handleTaskComment))
	api("POST", "/api/tasks/{id}/checklist", s.module("tasks", s.handleTaskChecklistAdd))
	api("POST", "/api/tasks/{id}/watch", s.module("tasks", s.handleTaskWatch))
	api("POST", "/api/tasks/{id}/attachments", s.module("tasks", s.handleTaskAttachmentAdd))
	api("POST", "/api/tasks/{id}/attachments/{att}/delete", s.module("tasks", s.handleTaskAttachmentDelete))
	api("POST", "/api/timesheet/edits", s.handleTimeEditCreate)
	api("POST", "/api/timesheet/edits/{id}/decision", s.manage(s.handleTimeEditDecision))
	api("POST", "/api/tasks/{id}/dependencies", s.module("tasks", s.handleTaskDependencyAdd))
	api("POST", "/api/tasks/{id}/dependencies/{dep}/delete", s.module("tasks", s.handleTaskDependencyDelete))
	api("POST", "/api/tasks/{id}/checklist/{item}/done", s.module("tasks", s.handleTaskChecklistSet))
	api("POST", "/api/tasks/{id}/checklist/{item}/delete", s.module("tasks", s.handleTaskChecklistDelete))
	api("GET", "/api/tasks/{id}/plan-move", s.module("tasks", s.handleTaskPlanMove))
	api("GET", "/api/tasks/report.csv", s.module("tasks", s.manage(s.handleTaskReportCSV)))
	api("POST", "/api/tasks/{id}/archive", s.module("tasks", s.handleTaskArchive))
	api("POST", "/api/tasks/{id}/restore", s.module("tasks", s.handleTaskRestore))
	api("POST", "/api/tasks/import/github", s.module("tasks", s.manage(s.handleTasksImportGitHub)))
	api("POST", workspaceRestorePath, s.module("import", s.handleWorkspaceRestore))
	api("POST", "/api/tasks/{id}/activities", s.module("tasks", s.handleTaskActivity))
	api("GET", "/api/tasks/{id}/linkable", s.module("tasks", s.handleTaskLinkable))
	api("GET", "/api/goals", s.module("goals", s.handleGoalsList))
	api("GET", "/api/goals/progress", s.module("goals", s.handleGoalsProgress))
	api("POST", "/api/goals", s.module("goals", s.manage(s.handleGoalsUpsert)))
	api("DELETE", "/api/goals", s.module("goals", s.manage(s.handleGoalsDelete)))
	api("GET", "/api/crm/deals", s.module("crm", s.handleCRMDealsList))
	api("POST", "/api/crm/deals", s.module("crm", s.handleCRMDealCreate))
	api("POST", "/api/crm/deals/{id}", s.module("crm", s.handleCRMDealUpdate))
	api("POST", "/api/crm/deals/{id}/stage", s.module("crm", s.handleCRMDealStage))
	api("POST", "/api/crm/deals/{id}/project", s.module("crm", s.handleCRMDealProject))
	api("GET", "/api/crm/stages", s.module("crm", s.handleCRMStagesList))
	api("POST", "/api/crm/stages", s.module("crm", s.manage(s.handleCRMStageCreate)))
	api("POST", "/api/crm/stages/{key}", s.module("crm", s.manage(s.handleCRMStageUpdate)))
	api("POST", "/api/crm/stages/{key}/delete", s.module("crm", s.manage(s.handleCRMStageDelete)))
	api("GET", "/api/crm/contacts", s.module("crm", s.handleCRMContactsList))
	api("POST", "/api/crm/contacts", s.module("crm", s.handleCRMContactCreate))
	api("GET", "/api/crm/activities", s.module("crm", s.handleCRMActivitiesList))
	api("POST", "/api/crm/activities", s.module("crm", s.handleCRMActivityCreate))
	api("GET", "/api/crm/leads", s.module("crm", s.handleCRMLeadsList))
	api("GET", "/api/crm/leads/response-stats", s.module("crm", s.handleCRMLeadResponseStats))
	api("GET", "/api/crm/report/funnel", s.module("crm", s.handleCRMFunnelReport))
	api("POST", "/api/crm/leads", s.module("crm", s.handleCRMLeadCreate))
	api("POST", "/api/crm/leads/{id}", s.module("crm", s.handleCRMLeadUpdate))
	api("POST", "/api/crm/leads/{id}/status", s.module("crm", s.handleCRMLeadStatus))
	api("POST", "/api/crm/leads/{id}/convert", s.module("crm", s.handleCRMLeadConvert))
	api("GET", "/api/crm/intake-key", s.module("crm", s.manage(s.handleCRMIntakeKeyStatus)))
	api("POST", "/api/crm/intake-key", s.module("crm", s.manage(s.handleCRMIntakeKeyCreate)))
	api("POST", "/api/crm/intake-key/revoke", s.module("crm", s.manage(s.handleCRMIntakeKeyRevoke)))
	api("GET", "/api/calendar/events", s.module("calendar", s.handleCalendarEventsList))
	api("POST", "/api/calendar/events", s.module("calendar", s.handleCalendarEventCreate))
	api("POST", "/api/calendar/events/{id}", s.module("calendar", s.handleCalendarEventUpdate))
	api("POST", "/api/calendar/events/{id}/delete", s.module("calendar", s.handleCalendarEventDelete))
	api("POST", "/api/calendar/sync", s.module("calendar", s.mine(s.handleCalendarSyncNow)))
	api("GET", "/api/tags", s.handleTagsList)
	api("POST", "/api/tags", s.handleTagsCreate)
	api("DELETE", "/api/tags", s.manage(s.handleTagsDelete))
	api("PATCH", "/api/tags", s.manage(s.handleTagsRename))
	api("POST", "/api/sessions/{id}/tags", s.handleSessionTagAdd)
	api("DELETE", "/api/sessions/{id}/tags", s.handleSessionTagRemove)

	// Workspace and profile management.
	api("POST", "/api/team/rename", s.manage(s.handleAPITeamRename))
	api("POST", "/api/team/currency", s.owner(s.handleAPITeamCurrency))
	api("POST", "/api/team/calendar", s.manage(s.handleAPITeamCalendar))
	api("POST", "/api/invoices/{id}/share", s.module("invoices", s.manage(s.handleInvoiceShare)))
	api("POST", "/api/day-marks", s.handleDayMark)
	api("GET", "/api/search", s.handleSearch)
	api("POST", "/api/clients/{id}/tags", s.handleClientTagsSet)
	api("POST", "/api/workday", s.handleWorkday)
	api("POST", "/api/team/requisites", s.manage(s.handleAPITeamRequisites))
	api("POST", "/api/team/modules", s.manage(s.handleAPITeamModules))
	api("POST", "/api/team/billing", s.owner(s.handleAPITeamBilling))
	api("POST", "/api/team/logo", s.manage(s.handleAPITeamLogo))
	api("POST", "/api/me/preferences", s.handleAPIPreferences)
	api("POST", "/api/team/create", s.handleAPITeamCreate)
	api("POST", "/api/team/switch", s.handleAPITeamSwitch)
	api("POST", "/api/team/delete", s.handleAPITeamDelete)
	api("DELETE", "/api/team", s.handleAPITeamDelete)
	api("POST", "/api/team/invites", s.manage(s.handleAPIInviteCreate))
	api("POST", "/api/team/invites/{token}/revoke", s.manage(s.handleAPIInviteRevoke))
	api("DELETE", "/api/team/invites/{token}", s.manage(s.handleAPIInviteRevoke))
	api("POST", "/api/team/members/{id}/remove", s.handleAPIMemberRemove)
	api("POST", "/api/team/members/{id}/role", s.manage(s.handleAPIMemberRole))
	api("POST", "/api/team/members/{id}/return", s.manage(s.handleAPIMemberReturn))
	api("POST", "/api/team/transfer", s.manage(s.handleAPITeamTransfer))
	api("POST", "/api/invites/{token}/accept", s.handleAPIInviteAccept)
	api("POST", "/api/profile", s.handleAPIProfileUpdate)
	api("POST", "/api/team/leave", s.handleAPITeamLeave)
	api("POST", "/api/profile/email", s.handleAPIProfileEmail)
	api("POST", "/api/profile/password", s.handleAPIProfilePassword)

	// Project API.
	api("GET", "/api/projects", s.handleAPIProjectsList)
	api("POST", "/api/projects", s.manage(s.handleAPIProjectCreate))
	api("PATCH", "/api/projects/{id}", s.manage(s.handleAPIProjectUpdate))
	api("DELETE", "/api/projects/{id}", s.manage(s.handleAPIProjectDelete))
	api("POST", "/api/activities/{id}/project", s.handleAPIAssignActivityProject)

	// Browser-extension endpoints use bearer API tokens.
	api("GET", "/api/me", s.handleAPIMe)
	api("GET", "/api/external-tasks", s.handleAPIExternalTasks)

	// Web Push API.
	api("GET", "/api/push/key", s.handlePushKey)
	api("POST", "/api/push/subscribe", s.handlePushSubscribe)
	api("POST", "/api/push/unsubscribe", s.handlePushUnsubscribe)
	api("POST", "/api/push/topics", s.handleNotificationTopics)
	api("POST", "/api/push/test", s.handleNotificationTest)

	// Versioned public API.
	api("GET", "/api/v1/sessions", s.handleAPIv1Sessions)
	api("POST", "/api/v1/sessions", s.handleAPIv1Sessions)
	api("PATCH", "/api/v1/sessions/{id}", s.handleAPIv1Session)
	api("DELETE", "/api/v1/sessions/{id}", s.handleAPIv1Session)
	api("GET", "/api/v1/projects", s.handleAPIv1Projects)
	api("GET", "/api/v1/reports/summary", s.handleAPIv1Report)
	api("GET", "/api/v1/clients", s.handleAPIv1Clients)
	api("GET", "/api/v1/me", s.handleAPIv1Me)
	api("GET", "/api/v1/members", s.handleAPIv1Members)
	api("GET", "/api/v1/tags", s.handleAPIv1Tags)
	api("GET", "/api/v1/tasks", s.module("tasks", s.handleAPIv1Tasks))

	// Agent endpoint: an API token only, and the rights are checked per tool.
	api("POST", "/mcp", mcpBearerOnly(s.handleMCP))

	// Every api registration above passes through apiAuth.
}
